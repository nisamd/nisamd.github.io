#!/bin/sh
# Regenerates assets/css/syntax.css: one Chroma style for the light theme, one for dark.
# Usage: sh scripts/syntax-css.sh [light-style] [dark-style]
# Styles: https://xyproto.github.io/splash/docs/
set -eu
cd "$(dirname "$0")/.."
light=${1:-github}
dark=${2:-nord}

# Prints style $2 with every selector prefixed by $1. The block background is
# dropped because the site sets its own (--code-bg in main.css).
scope() {
  hugo gen chromastyles --style="$2" |
    grep -v -e '^/\* Background \*/' -e '^/\* Generated' |
    sed -e '/^\/\* PreWrapper \*\//s/background-color:[^;}]*;\{0,1\}//' |
    awk -v pre="$1" '
      /\{/ {
        i = index($0, "*/"); j = index($0, "{")
        sel = substr($0, i + 2, j - i - 2); rest = substr($0, j)
        n = split(sel, parts, ",")
        out = ""
        for (k = 1; k <= n; k++) {
          gsub(/^ +| +$/, "", parts[k])
          out = out (k > 1 ? ", " : "") (pre == "" ? "" : pre " ") parts[k]
        }
        print out " " rest
      }'
}

{
  echo "/* Generated by scripts/syntax-css.sh ($light / $dark). Do not edit by hand. */"
  # Same theme rules as the color tokens in main.css, so neither style leaks into the other.
  echo '@media not (prefers-color-scheme: dark) {'
  scope ':root:not([data-theme="dark"])' "$light"
  echo '}'
  scope ':root[data-theme="light"]' "$light"
  echo '@media (prefers-color-scheme: dark) {'
  scope ':root:not([data-theme="light"])' "$dark"
  echo '}'
  scope ':root[data-theme="dark"]' "$dark"
} > assets/css/syntax.css
echo "wrote assets/css/syntax.css"
